# 函数：make_examples
# 功能：为一组 FAQ 生成训练句对——正例=同 FAQ 内部任意两句两两配对（意图相同、
#       问法不同），负例=该 FAQ 标准问与其他 FAQ 标准问的跨意图配对
# 流水线位置：核心数据构造逻辑，被 main() 按每个 split 分别调用
# 输入：faq_ids=本 split 的 FAQ 编号；rng=随机源；neg_per_faq=每条 FAQ 负例采样数
# 输出：打乱后的句对列表 [{sentence1, sentence2, label}, ...]
# ═══════════════════════════════════════════════════════════════════════════
def make_examples(faq_ids, rng, neg_per_faq):
    """为给定 FAQ 集合生成正负例（正例=同 FAQ 内部两两，负例=跨 FAQ 标准问）"""
    faq_by_id = {f["id"]: f for f in FAQS}              # 构建 id → FAQ 字典，后续 O(1) 查表
    all_ids = [f["id"] for f in FAQS]                  # 全库 30 个 FAQ 编号（负例采样池）

    positive, negative = [], []                        # 正例、负例两个累积列表
    for fid in faq_ids:                                # 只为本 split 拥有的 FAQ 造数据（防泄漏）
        f = faq_by_id[fid]                             # 取出当前 FAQ
        sents = [f["question"]] + f["variants"]        # 该 FAQ 全部问法 = 标准问 + 3 条改写，共 4 句

        # 正例：同一条 FAQ 内所有两两配对（意图相同、问法不同）
        for i in range(len(sents)):                    # 第一句下标 i
            for j in range(i + 1, len(sents)):         # 第二句下标 j 严格大于 i（避免重复/自配对）
                positive.append({"sentence1": sents[i], "sentence2": sents[j], "label": 1})  # 4 句共 C(4,2)=6 条正例

        # 负例：标准问与其他 FAQ 的标准问配对（意图不同）
        others = [x for x in all_ids if x != fid]      # 排除自己后的其余 29 个 FAQ 编号
        for q2 in [faq_by_id[o]["question"] for o in rng.sample(others, neg_per_faq)]:  # 随机抽 neg_per_faq 个（29 抽 12），取出其标准问
            negative.append({"sentence1": f["question"], "sentence2": q2, "label": 0})  # 当前标准问 × 他 FAQ 标准问，label=0

    examples = positive + negative                     # 合并正负例（此刻正例在前、负例在后）
    rng.shuffle(examples)                              # 原地打乱，避免训练时同标签样本连续聚集
    return examples                                    # 返回该 split 的全部句对


# ═══════════════════════════════════════════════════════════════════════════
# 函数：main
# 功能：数据集构建总入口——固定随机种子，按 FAQ 维度 8:1:1 切分并逐 split
#       生成句对落盘，最后把 FAQS 原样保存为 faq.json 知识库
# 流水线位置：本脚本唯一入口；产物直接被训练脚本（src/train_*.py）与
#            检索程序（faq_answer.py）消费
# 输入：无（种子数据 FAQS 硬编码）　输出：data/blood_pressure/ 下 4 个文件
# ═══════════════════════════════════════════════════════════════════════════
def main():
    """按 FAQ 维度 8:1:1 切分并生成 train/validation/test JSONL 与 faq.json。"""
    rng = random.Random(42)                            # 独立随机源，种子固定 42（任何人重跑结果一致）

    # 按 FAQ 维度切分（8:1:1），避免同一条 FAQ 泄漏到不同 split
    # 切分单位是"整条 FAQ"而非"单个句对"：同一条 FAQ 的所有问法只会落进一个
    # split，防止模型在评估集里"见过同一句话"而作弊得分（导致指标虚高失真）。
    ids = [f["id"] for f in FAQS]                      # 全部 30 个 FAQ 编号
    rng.shuffle(ids)                                   # 打乱编号顺序（决定各 split 成员）
    n = len(ids)                                       # FAQ 总数 30
    n_train, n_val = int(n * 0.8), int(n * 0.1)        # 训练 24 条 / 验证 3 条（int 向下取整）
    train_ids = ids[:n_train]                          # 前 24 个编号 → 训练集
    val_ids = ids[n_train:n_train + n_val]             # 接着 3 个编号 → 验证集
    test_ids = ids[n_train + n_val:]                   # 剩余 3 个编号 → 测试集

    print(f"共 {n} 条 FAQ -> train {len(train_ids)} / val {len(val_ids)} / test {len(test_ids)}")  # 打印切分概览

    for split, sids in [("train", train_ids), ("validation", val_ids), ("test", test_ids)]:  # 三个 split 逐一构建
        examples = make_examples(sids, rng, neg_per_faq=12)     # 生成该 split 的正负例句对
        save_jsonl(examples, DATA_DIR / f"{split}.jsonl")      # 落盘为 data/blood_pressure/{split}.jsonl
        pos = sum(1 for e in examples if e["label"] == 1)      # 统计正例条数
        neg = len(examples) - pos                               # 负例条数 = 总数 - 正例
        print(f"  {split:10s}: {len(examples):>4} 条  正例 {pos:>4}  负例 {neg:>4}")  # 打印该 split 规模统计

    # 保存 FAQ 库（供 faq_answer.py 检索回答）
    faq_path = DATA_DIR / "faq.json"                   # 知识库文件路径
    with open(faq_path, "w", encoding="utf-8") as f:    # UTF-8 覆盖写打开
        json.dump(FAQS, f, ensure_ascii=False, indent=2)  # 30 条 FAQ 原样写出（中文不转义、缩进 2 空格）
    print(f"\nFAQ 库 -> {faq_path}")                   # 打印知识库产出位置
    print(f"数据目录 -> {DATA_DIR}")                   # 打印数据目录


if __name__ == "__main__":                             # 直接运行本脚本时才执行（被 import 时不触发）
    main()                                             # 调用主流程
