# ═══════════════════════════════════════════════════════════════════════════
# 函数：save_jsonl
# 功能：把"字典列表"逐行写成 JSONL 文件（每行一个独立 JSON 对象，带换行符）
# 流水线位置：被 main() 调用，负责落盘 train/validation/test 三个 .jsonl
# 输入：rows=样例字典列表；path=目标文件路径　输出：无（写文件，自动建父目录）
# ═══════════════════════════════════════════════════════════════════════════
def save_jsonl(rows, path):
    """把行列表逐行序列化为 JSON 写入指定 JSONL 文件（自动创建父目录）。"""
    path.parent.mkdir(parents=True, exist_ok=True)    # 递归创建父目录（已存在则不报错）
    with open(path, "w", encoding="utf-8") as f:       # 以 UTF-8 覆盖写方式打开目标文件
        for row in rows:                               # 逐条遍历样例字典
            f.write(json.dumps(row, ensure_ascii=False) + "\n")  # 序列化为单行 JSON（中文原样不转义）+ 换行符


